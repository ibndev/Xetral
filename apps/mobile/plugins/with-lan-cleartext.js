const { withAndroidManifest, withDangerousMod, AndroidConfig } = require('@expo/config-plugins');
const { mkdirSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');

/**
 * Lets a RELEASE build talk to the ONE http address it was built for, and to
 * nothing else in plaintext.
 *
 * THE FAILURE THIS PREVENTS looks exactly like a broken app. Android has
 * refused cleartext HTTP by default since API 28, and Expo's template enables
 * it only in the DEBUG manifest. So a release APK built against
 * `http://192.168.1.20:3100` installs, opens, renders every screen perfectly —
 * and every request dies with a network error. Nothing in the build reports a
 * problem, because nothing about the build is wrong.
 *
 * THE EXCEPTION IS THE BUILD'S OWN HOST, and this is the second version of
 * this file. The first listed the private ranges as CIDR blocks
 * (`192.168.0.0/16` and friends), which reads perfectly and does nothing:
 * Android's `<domain>` element takes a HOSTNAME OR A LITERAL ADDRESS, and has
 * no notion of a subnet. It would have failed in precisely the way this plugin
 * exists to prevent — a config that looks like it permits the connection while
 * the connection is refused.
 *
 * So the host is taken from `EXPO_PUBLIC_API_URL`: the same value the bundle
 * is compiled with, which means the exception cannot be for an address the app
 * is not going to call. An `https` URL adds no exception at all, and a build
 * with no URL set adds none either — in both cases Android's default stands
 * and every plaintext connection is refused.
 */

/** The emulator's alias for the machine running it, which is not discoverable
 *  from the URL because a developer types `localhost` and means this. */
const ALWAYS = ['10.0.2.2', 'localhost', '127.0.0.1'];

function cleartextHostFrom(rawUrl) {
  if (typeof rawUrl !== 'string' || rawUrl === '') return undefined;
  let parsed;
  try {
    parsed = new URL(rawUrl);
  } catch {
    // Not our error to raise: the app itself refuses to start without a usable
    // URL, and failing prebuild here would report a bad address as a plugin
    // crash.
    return undefined;
  }
  // https needs no exception. Adding one anyway would weaken a build that did
  // not need weakening.
  return parsed.protocol === 'http:' ? parsed.hostname : undefined;
}

function configFor(hosts) {
  const domains = hosts
    .map((host) => `        <domain includeSubdomains="false">${host}</domain>`)
    .join('\n');

  return `<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by plugins/with-lan-cleartext.js from EXPO_PUBLIC_API_URL.
  Do not edit: android/ is rebuilt from app.json by \`expo prebuild --clean\`.

  Everything not listed here keeps Android's default, which is that plaintext
  is refused. This app carries a bearer token, so a blanket
  usesCleartextTraffic="true" would be the wrong trade for the convenience of
  testing against a laptop.
-->
<network-security-config>
    <domain-config cleartextTrafficPermitted="true">
${domains}
    </domain-config>
</network-security-config>
`;
}

const withLanCleartext = (config) => {
  const host = cleartextHostFrom(process.env['EXPO_PUBLIC_API_URL']);
  const hosts = [...new Set([...ALWAYS, ...(host === undefined ? [] : [host])])];

  // Said out loud during prebuild. A silent exception is one nobody reviews,
  // and this is the line a reader should see in a build log before installing
  // the result on a phone.
  if (host === undefined) {
    console.log(
      '[with-lan-cleartext] EXPO_PUBLIC_API_URL is https or unset: ' +
        'plaintext stays refused except for the emulator loopback.',
    );
  } else {
    console.log(`[with-lan-cleartext] permitting cleartext to ${host} only`);
  }

  // `withDangerousMod` is the sanctioned way to put a file into the generated
  // project: there is no typed modifier for an arbitrary XML resource, and
  // writing outside this hook would run before prebuild had made the directory.
  config = withDangerousMod(config, [
    'android',
    (cfg) => {
      const dir = join(cfg.modRequest.platformProjectRoot, 'app/src/main/res/xml');
      mkdirSync(dir, { recursive: true });
      writeFileSync(join(dir, 'network_security_config.xml'), configFor(hosts));
      return cfg;
    },
  ]);

  return withAndroidManifest(config, (cfg) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    application.$['android:networkSecurityConfig'] = '@xml/network_security_config';
    return cfg;
  });
};

module.exports = withLanCleartext;
